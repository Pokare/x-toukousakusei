/** 細かいギザギザを抑えるため、閉じた点列を1回だけならす（隣の点へ少し寄せる） */
const relax = (pts: [number, number][], w = 0.2): [number, number][] =>
  pts.map((q, i) => {
    const a = pts[(i - 1 + pts.length) % pts.length];
    const b = pts[(i + 1) % pts.length];
    return [q[0] * (1 - 2 * w) + (a[0] + b[0]) * w, q[1] * (1 - 2 * w) + (a[1] + b[1]) * w];
  });

/** 閉じた点列を Catmull-Rom → 3次ベジェの SVG パスにする */
const smoothClosed = (pts: [number, number][]): string => {
  const n = pts.length;
  const p = (i: number) => pts[(i + n) % n];
  const f = (v: number) => v.toFixed(1);
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = p(i - 1);
    const p1 = p(i);
    const p2 = p(i + 1);
    const p3 = p(i + 2);
    const c1x = p1[0] + (p2[0] - p0[0]) / 6;
    const c1y = p1[1] + (p2[1] - p0[1]) / 6;
    const c2x = p2[0] - (p3[0] - p1[0]) / 6;
    const c2y = p2[1] - (p3[1] - p1[1]) / 6;
    d += `C${f(c1x)} ${f(c1y)} ${f(c2x)} ${f(c2y)} ${f(p2[0])} ${f(p2[1])}`;
  }
  return `${d}Z`;
};

