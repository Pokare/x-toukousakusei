// 実際の経度・緯度から手で拾った点を、元動画と同じ見え方になるように投影する:
//   正距円筒図法（経度方向に cos(36°) を掛ける）→ 時計回りに 30° 回転 → 1度 ≈ 25.9px。
// 元動画の地図もこの投影で、東京・大阪・福岡のピン位置が実座標どおりに一致する。
// 点列は Catmull-Rom で滑らかな閉曲線（3次ベジェ）にする。

type LonLat = readonly [number, number];

// 投影の基準（元動画の東京ピンの位置 = 画面座標 971, 797.5）
const REF_LON = 139.69;
const REF_LAT = 35.69;
const REF_X = 971;
const REF_Y = 797.5;
const PX_PER_DEG = 25.9;
const COS_LAT = Math.cos((36 * Math.PI) / 180);
const ROT = (30 * Math.PI) / 180;

export const project = ([lon, lat]: LonLat): [number, number] => {
  const dx = (lon - REF_LON) * COS_LAT;
  const dy = -(lat - REF_LAT);
  const x = dx * Math.cos(ROT) - dy * Math.sin(ROT);
  const y = dx * Math.sin(ROT) + dy * Math.cos(ROT);
  return [REF_X + x * PX_PER_DEG, REF_Y + y * PX_PER_DEG];
};

